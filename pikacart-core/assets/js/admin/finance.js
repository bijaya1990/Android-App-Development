/**
 * Monthly statement downloads (Excel and PDF), made in the browser.
 */

const { __ } = window.wp.i18n;
const cfg = window.PKC;
const st = cfg.statement;
const biz = cfg.business;

const rupees = ( paise ) => ( paise / 100 ).toFixed( 2 );
const money = ( paise ) => ( paise < 0 ? '-' : '' ) + 'Rs ' + Math.abs( paise / 100 ).toLocaleString( 'en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 } );
const head = () => [ __( 'Date', 'pikacart' ), __( 'Payments', 'pikacart' ), __( 'Income', 'pikacart' ), __( 'Refunds', 'pikacart' ), __( 'Expenses', 'pikacart' ), __( 'Net', 'pikacart' ) ];

function excel() {
	const rows = [
		[ `${ biz.name } · ${ __( 'Account statement', 'pikacart' ) } · ${ st.label }` ],
		[],
		head(),
		...st.days.map( ( d ) => [ d.date, d.count, Number( rupees( d.income ) ), Number( rupees( d.refunds ) ), Number( rupees( d.expenses ) ), Number( rupees( d.net ) ) ] ),
		[ __( 'Total', 'pikacart' ), st.totals.count, Number( rupees( st.totals.income ) ), Number( rupees( st.totals.refunds ) ), Number( rupees( st.totals.expenses ) ), Number( rupees( st.totals.net ) ) ],
	];
	const ws = window.XLSX.utils.aoa_to_sheet( rows );
	ws[ '!cols' ] = [ { wch: 14 }, { wch: 10 }, { wch: 12 }, { wch: 12 }, { wch: 12 }, { wch: 12 } ];
	const wb = window.XLSX.utils.book_new();
	window.XLSX.utils.book_append_sheet( wb, ws, st.month );
	window.XLSX.writeFile( wb, `statement-${ st.month }.xlsx` );
}

function pdf() {
	const { jsPDF } = window.jspdf;
	const doc = new jsPDF( { unit: 'mm', format: 'a4' } );
	const L = 14;
	const R = 196;
	let y = 18;
	doc.setFont( 'helvetica', 'bold' );
	doc.setFontSize( 16 );
	doc.text( biz.name, L, y );
	doc.setFontSize( 11 );
	doc.text( __( 'Account statement', 'pikacart' ) + ' · ' + st.label, R, y, { align: 'right' } );
	doc.setFont( 'helvetica', 'normal' );
	doc.setFontSize( 9 );
	y += 6;
	( biz.address || '' ).split( /\n/ ).filter( Boolean ).forEach( ( line ) => {
		doc.text( line, L, y );
		y += 4.5;
	} );
	if ( biz.gstin ) {
		doc.text( 'GSTIN: ' + biz.gstin, L, y );
		y += 4.5;
	}
	y += 4;

	// Summary boxes.
	const boxes = [ [ __( 'Income', 'pikacart' ), st.totals.income ], [ __( 'Refunds', 'pikacart' ), st.totals.refunds ], [ __( 'Expenses', 'pikacart' ), st.totals.expenses ], [ __( 'Net profit', 'pikacart' ), st.totals.net ] ];
	const bw = ( R - L - 9 ) / 4;
	boxes.forEach( ( b, i ) => {
		const x = L + i * ( bw + 3 );
		doc.setFillColor( 244, 245, 249 );
		doc.roundedRect( x, y, bw, 16, 2, 2, 'F' );
		doc.setFontSize( 8 );
		doc.setTextColor( 107, 112, 128 );
		doc.text( b[ 0 ], x + 3, y + 5.5 );
		doc.setFontSize( 11 );
		doc.setTextColor( 31, 36, 51 );
		doc.setFont( 'helvetica', 'bold' );
		doc.text( money( b[ 1 ] ), x + 3, y + 12 );
		doc.setFont( 'helvetica', 'normal' );
	} );
	y += 24;

	const cols = [ L, L + 40, L + 66, L + 96, L + 126, R ];
	const row = ( cells, bold ) => {
		doc.setFont( 'helvetica', bold ? 'bold' : 'normal' );
		cells.forEach( ( c, i ) => doc.text( String( c ), i === 0 ? cols[ 0 ] : ( i === cells.length - 1 ? R : cols[ i + 1 ] - 4 ), y, { align: i === 0 ? 'left' : 'right' } ) );
		y += 5.6;
	};
	doc.setFontSize( 9 );
	doc.setFillColor( 79, 70, 229 );
	doc.rect( L - 2, y - 4, R - L + 4, 7, 'F' );
	doc.setTextColor( 255, 255, 255 );
	row( head(), true );
	doc.setTextColor( 31, 36, 51 );
	st.days.forEach( ( d, i ) => {
		if ( y > 280 ) {
			doc.addPage();
			y = 18;
		}
		if ( i % 2 ) {
			doc.setFillColor( 248, 249, 252 );
			doc.rect( L - 2, y - 4, R - L + 4, 5.6, 'F' );
		}
		row( [ d.date, d.count, money( d.income ), money( d.refunds ), money( d.expenses ), money( d.net ) ] );
	} );
	doc.setDrawColor( 200, 200, 210 );
	doc.line( L - 2, y - 3.5, R + 2, y - 3.5 );
	row( [ __( 'Total', 'pikacart' ), st.totals.count, money( st.totals.income ), money( st.totals.refunds ), money( st.totals.expenses ), money( st.totals.net ) ], true );
	doc.setFontSize( 8 );
	doc.setTextColor( 107, 112, 128 );
	doc.text( __( 'Generated by Pikacart on', 'pikacart' ) + ' ' + new Date().toLocaleString( 'en-IN' ), L, 290 );
	doc.save( `statement-${ st.month }.pdf` );
}

document.querySelectorAll( '[data-dl]' ).forEach( ( b ) => b.addEventListener( 'click', () => ( b.dataset.dl === 'pdf' ? pdf() : excel() ) ) );
